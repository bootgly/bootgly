namespace Bootgly\WPI\Nodes\HTTP_Server_CLI\ACME_Client\Tests;


use function assert;
use function debug_zval_dump;
use function implode;
use function ob_get_clean;
use function ob_start;
use function print_r;
use function str_contains;
use function var_dump;
use ReflectionClass;
use ReflectionMethod;
use ReflectionProperty;

use Bootgly\ABI\Debugging\Data\Vars\Dumper;
use Bootgly\ABI\Debugging\Data\Vars\Redactable;
use Bootgly\ABI\Debugging\Data\Vars\Redactable\Secret;
use Bootgly\ACI\Tests\Suite\Test;
use Bootgly\WPI\Nodes\HTTP_Server_CLI\ACME_Client\CSR;


/**
 * A CSR keeps the private key of the certificate it requests. A debug dump of
 * a CSR masks that key, while its domains still show — and the dump runs no
 * hook: a CSR whose key was never generated stays ungenerated.
 */
return new Test(
   description: 'ACME CSR: debug dumps mask the certificate private key and never generate one',
   test: function () {
      // ! SYNTH key material — never a real key; the PEM label is built so the tree's key guard
      //   (API Environment `1.5-tracked-certificates`) never meets a key marker in this file
      $label = 'PRIVATE KEY';
      $PEM = "-----BEGIN {$label}-----\nSYNTH-ACME-CSR-KEY-6.1\n-----END {$label}-----\n";
      $Dumper = new Dumper('plain');
      // ! No limit may hide a leak
      $Dumper->depth = 32;
      $Dumper->strings = 1_000_000;
      $Dumper->items = 10_000;
      // ! Each debug channel
      $Channels = [
         'var_dump' => static function (object $Object): string {
            ob_start();
            var_dump($Object);

            return (string) ob_get_clean();
         },
         'print_r' => static fn (object $Object): string => print_r($Object, true),
         'debug_zval_dump' => static function (object $Object): string {
            ob_start();
            debug_zval_dump($Object);

            return (string) ob_get_clean();
         },
         'Dumper' => static fn (object $Object): string => $Dumper->dump($Object),
      ];
      $Key = new ReflectionProperty(CSR::class, 'key');

      // @ A dump runs no hook: the key of a fresh CSR is not generated by it
      $Fresh = new CSR(['fresh.example.invalid']);
      foreach ($Channels as $Channel) {
         $Channel($Fresh);
      }
      yield assert(
         assertion: $Key->isInitialized($Fresh) === false,
         description: 'Dumping a fresh CSR generates no key'
      );

      // ! A CSR holding its key — seated directly, no RSA generation
      $CSR = new CSR(['visible.example.invalid']);
      $Key->setValue($CSR, $PEM);

      // @@ Every channel
      $leaks = [];
      $missing = [];
      foreach ($Channels as $channel => $Channel) {
         $output = $Channel($CSR);

         if (str_contains($output, 'SYNTH-ACME-CSR-KEY-6.1') === true) {
            $leaks[] = $channel;
         }
         foreach (['visible.example.invalid', Secret::MASK] as $shown) {
            if (str_contains($output, $shown) === false) {
               $missing[] = "{$shown} via {$channel}";
            }
         }
      }
      $leaked = implode(', ', $leaks);
      $absent = implode(', ', $missing);
      yield assert(
         assertion: $leaks === [] && $missing === [],
         description: "The private key reaches no debug channel, while the domains show (leaked via: [{$leaked}], missing: [{$absent}])"
      );

      // @ Dumping never writes
      yield assert(
         assertion: $CSR->key === $PEM,
         description: 'The live private key is untouched by the dumps'
      );

      // @ The one way: the trait's __debugInfo, #[Secret] on the stored key only
      $Own = new ReflectionMethod($CSR, '__debugInfo');
      $Trait = new ReflectionMethod(Redactable::class, '__debugInfo');
      $marked = [];
      $misplaced = [];
      foreach ((new ReflectionClass(CSR::class))->getProperties() as $Property) {
         if ($Property->getAttributes(Secret::class) === []) {
            continue;
         }

         $marked[] = $Property->name;
         if ($Property->isStatic() === true || $Property->isVirtual() === true) {
            $misplaced[] = $Property->name;
         }
      }
      yield assert(
         assertion: $Own->getFileName() === $Trait->getFileName()
            && $Own->getStartLine() === $Trait->getStartLine()
            && $marked === ['key']
            && $misplaced === [],
         description: 'CSR dumps through the Redactable trait, #[Secret] on the stored key only'
      );
   }
);
